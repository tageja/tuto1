#!/usr/bin/env node
// Reads every tests/e2e/<dir>/<file>.spec.ts file, extracts its TAGs,
// and writes tests/COVERAGE.md showing which (module x concern) cells are covered.
//
// Run: npm run test:coverage
//
// Heuristics:
//   - Looks for `TAG.x` references inside the file source.
//   - Cross-cutting tests count toward the cross-cutting row.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\//, '').replace(/\//g, '\\');
const E2E_DIR = ROOT + 'e2e';
const OUT = ROOT + 'COVERAGE.md';

const MODULES = ['module-1','module-2','module-3','module-4','module-5','module-6','module-7','module-8','module-9','module-10','module-11','module-12','cross-cutting'];
const CONCERNS = ['a11y','content','state','nav','i18n','visual','data','auth','audio'];

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith('.spec.ts')) out.push(full);
  }
  return out;
}

function extractTags(src) {
  const tags = new Set();
  for (const m of src.matchAll(/TAG\.([a-zA-Z0-9_]+)/g)) tags.add(m[1]);
  for (const m of src.matchAll(/bugTag\((\d+)\)/g)) tags.add('bug-' + m[1]);
  const norm = new Set();
  for (const t of tags) {
    if (t === 'module1') norm.add('module-1');
    else if (t === 'module2') norm.add('module-2');
    else if (t === 'module3') norm.add('module-3');
    else if (t === 'module4') norm.add('module-4');
    else if (t === 'module5') norm.add('module-5');
    else if (t === 'module6') norm.add('module-6');
    else if (t === 'module7') norm.add('module-7');
    else if (t === 'module8') norm.add('module-8');
    else if (t === 'module9') norm.add('module-9');
    else if (t === 'module10') norm.add('module-10');
    else if (t === 'module11') norm.add('module-11');
    else if (t === 'module12') norm.add('module-12');
    else if (t === 'crossCutting') norm.add('cross-cutting');
    else if (t === 'happyPath') norm.add('happy-path');
    else norm.add(t);
  }
  return norm;
}

const files = await walk(E2E_DIR);
const grid = {};
for (const m of MODULES) {
  grid[m] = Object.fromEntries(CONCERNS.map((c) => [c, []]));
}

for (const f of files) {
  const src = await readFile(f, 'utf8');
  const tags = extractTags(src);
  const moduleTags = MODULES.filter((m) => tags.has(m));
  const concerns = CONCERNS.filter((c) => tags.has(c));
  const targetModules = moduleTags.length ? moduleTags : tags.has('cross-cutting') ? ['cross-cutting'] : ['cross-cutting'];
  const rel = relative(ROOT, f).replaceAll('\\', '/');
  for (const m of targetModules) {
    for (const c of concerns) {
      grid[m][c].push(rel);
    }
  }
}

let md = '# Test Coverage Matrix\n\n';
md += `_Auto-generated by \`npm run test:coverage\` — do not edit by hand._\n\n`;
md += `**Scanned ${files.length} spec files.**\n\n`;
md += '| Scope ↓ / Concern → | ' + CONCERNS.join(' | ') + ' |\n';
md += '|---|' + CONCERNS.map(() => '---').join('|') + '|\n';
for (const m of MODULES) {
  const row = CONCERNS.map((c) => (grid[m][c].length ? `✓ (${grid[m][c].length})` : '·'));
  md += `| **${m}** | ` + row.join(' | ') + ' |\n';
}

md += '\n## Coverage gaps (priority order)\n\n';
const gaps = [];
for (const m of MODULES) {
  for (const c of CONCERNS) {
    if (grid[m][c].length === 0) gaps.push(`- [ ] **${m}** × **${c}**`);
  }
}
md += gaps.length ? gaps.join('\n') + '\n' : '_All cells covered — but coverage ≠ correctness, keep adding._\n';

md += '\n## Per-cell test lists\n\n';
for (const m of MODULES) {
  const cells = CONCERNS.filter((c) => grid[m][c].length);
  if (!cells.length) continue;
  md += `### ${m}\n\n`;
  for (const c of cells) {
    md += `- **${c}**: ` + grid[m][c].map((f) => `\`${f}\``).join(', ') + '\n';
  }
  md += '\n';
}

await writeFile(OUT, md);
console.log(`Wrote ${OUT} (${files.length} specs)`);
