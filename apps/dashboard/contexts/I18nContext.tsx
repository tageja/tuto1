const dicts: Record<Lang, Dict> = { vi, en };

interface I18nContextValue {
  lang: Lang;
  t: (k: keyof typeof en) => string;
  setLang: (l: Lang) => void;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode; defaultLang?: Lang }> = ({ children, defaultLang = 'vi' }) => {
  const [lang, setLangState] = useState<Lang>(defaultLang);
  React.useEffect(() => {
    try {
      const cookie = typeof document !== 'undefined' ? document.cookie.match(/(?:^|; )lang=([^;]+)/) : null;
      const saved = cookie ? decodeURIComponent(cookie[1]) : (typeof localStorage !== 'undefined' ? localStorage.getItem('lang') : null);
      if (saved === 'en' || saved === 'vi') setLangState(saved);
    } catch {}
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      if (typeof localStorage !== 'undefined') localStorage.setItem('lang', l);
      if (typeof document !== 'undefined') {
        const d = new Date();
        d.setTime(d.getTime() + 365 * 24 * 60 * 60 * 1000);
        document.cookie = `lang=${encodeURIComponent(l)}; expires=${d.toUTCString()}; path=/`;
      }
    } catch {}
  };
  const t = useMemo(() => (key: keyof typeof en) => dicts[lang][key] || key, [lang]);
  const value = useMemo(() => ({ lang, t, setLang }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
};


