// Nested dictionaries from JSON files
const vi: Dict = (viTranslations as any).default || viTranslations;
const en: Dict = (enTranslations as any).default || enTranslations;

// Helper function to get nested value from dot notation
function getNestedValue(obj: any, path: string): string | undefined {
  const keys = path.split('.');
  let current = obj;
  
  for (const key of keys) {
    if (current && typeof current === 'object' && key in current) {
      current = current[key];
    } else {
      return undefined;
    }
  }
  
  return typeof current === 'string' ? current : undefined;
}

interface I18nContextValue {
  lang: Lang;
  t: (key: string) => string;
  setLang: (l: Lang) => void;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode; defaultLang?: Lang }> = ({ children, defaultLang = 'vi' }) => {
  const [lang, setLangState] = useState<Lang>('vi');
  React.useEffect(() => {
    try {
      const cookie = typeof document !== 'undefined' ? document.cookie.match(/(?:^|; )lang=([^;]+)/) : null;
      const saved = cookie ? decodeURIComponent(cookie[1]) : (typeof localStorage !== 'undefined' ? localStorage.getItem('lang') : null);
      // Only use saved preference if it exists and is valid, otherwise default to Vietnamese
      if (saved === 'en' || saved === 'vi') {
        setLangState(saved);
      } else {
        // If no saved preference, set Vietnamese as default
        setLangState('vi');
      }
    } catch {
      // On error, default to Vietnamese
      setLangState('vi');
    }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      if (typeof localStorage !== 'undefined') localStorage.setItem('lang', l);
      if (typeof document !== 'undefined') {
        const d = new Date();
        d.setTime(d.getTime() + 365 * 24 * 60 * 60 * 1000);
        document.cookie = `lang=${encodeURIComponent(l)}; expires=${d.toUTCString()}; path=/`;
      }
    } catch {}
  };
  const t = useMemo(() => (key: string) => {
    // First try nested JSON structure
    const nested = getNestedValue(lang === 'vi' ? vi : en, key);
    if (nested) return nested;
    
    // Fallback to flat dictionary for backward compatibility
    // Handle nested keys by taking the last part if not found in nested structure
    const lastPart = key.split('.').pop() || key;
    const flat = (lang === 'vi' ? viFlat : enFlat)[lastPart] || (lang === 'vi' ? viFlat : enFlat)[key];
    if (flat) return flat;
    
    // Return key as fallback
    return key;
  }, [lang]);
  const value = useMemo(() => ({ lang, t, setLang }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
};


